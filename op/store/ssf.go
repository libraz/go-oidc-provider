package store

import (
	"context"
	"time"
)

// SharedSignalsStore is the extension of the aggregate [Store] that
// persists Shared Signals Framework 1.0 transmitter state: the streams
// receivers configure and the queue of Security Event Tokens waiting to
// be delivered to them.
//
// op.New requires it when op.WithSharedSignals is set, and additionally
// requires both accessors to return a non-nil substore. A partial-coverage
// backend (for example one composed from several stores) whose routed
// backend has no SSF support returns nil from the accessor, which op.New
// rejects at construction rather than at the first delivery.
//
// Stable since v1.5.
type SharedSignalsStore interface {
	Store

	// SSFStreams returns the stream configuration substore.
	SSFStreams() SSFStreamStore

	// SSFEvents returns the outbound Security Event Token queue.
	SSFEvents() SSFEventStore
}

// SSFDeliveryMethod names how a stream's events reach its receiver.
//
// Stable since v1.5.
type SSFDeliveryMethod string

// SSF delivery methods.
const (
	// SSFDeliveryPush delivers each event as an RFC 8935 HTTP POST to the
	// receiver's endpoint.
	//
	// Stable since v1.5.
	SSFDeliveryPush SSFDeliveryMethod = "push"

	// SSFDeliveryPoll holds each event until the receiver fetches it
	// through the RFC 8936 poll endpoint.
	//
	// Stable since v1.5.
	SSFDeliveryPoll SSFDeliveryMethod = "poll"
)

// SSFStreamStatus is the transmitter-side status of a stream (SSF 1.0
// §8.1.2).
//
// Stable since v1.5.
type SSFStreamStatus string

// SSF stream statuses.
const (
	// SSFStreamEnabled delivers every event as it is enqueued.
	//
	// Stable since v1.5.
	SSFStreamEnabled SSFStreamStatus = "enabled"

	// SSFStreamPaused holds ordinary events until the stream is enabled
	// again. Control events are still delivered.
	//
	// Stable since v1.5.
	SSFStreamPaused SSFStreamStatus = "paused"

	// SSFStreamDisabled drops ordinary events. Control events are still
	// delivered.
	//
	// Stable since v1.5.
	SSFStreamDisabled SSFStreamStatus = "disabled"
)

// SSFDelivery is the delivery configuration of a stream.
//
// Stable since v1.5.
type SSFDelivery struct {
	// Method is how the stream's events reach the receiver.
	Method SSFDeliveryMethod

	// EndpointURL is the receiver's push endpoint. Empty for poll
	// streams, whose poll endpoint the OP derives from the stream ID.
	EndpointURL string

	// SealedAuthorizationHeader is the receiver-supplied Authorization
	// header value for push requests, sealed by the library with
	// AES-256-GCM. Backends store and return the bytes verbatim and
	// MUST NOT inspect them. Nil means no header is sent.
	SealedAuthorizationHeader []byte
}

// SSFStream is the persistent representation of one SSF stream. A
// receiver is an OAuth client of this OP and owns at most one stream.
//
// Stable since v1.5.
type SSFStream struct {
	// ID is the stream_id, generated by the library. Primary key.
	ID string

	// ClientID is the receiver that owns the stream and the aud of
	// every event it carries. Unique across streams and never changed
	// after Create.
	ClientID string

	// Delivery is the stream's delivery configuration.
	Delivery SSFDelivery

	// EventsRequested is the receiver's events_requested, verbatim.
	EventsRequested []string

	// EventsDelivered is the subset of EventsRequested the transmitter
	// delivers.
	EventsDelivered []string

	// Description is the receiver-supplied description.
	Description string

	// Status is the stream's current status.
	Status SSFStreamStatus

	// StatusReason is the reason recorded with the last status change.
	StatusReason string

	// CreatedAt and UpdatedAt are stamped by the library.
	CreatedAt, UpdatedAt time.Time
}

// SSFStreamStore persists SSF streams.
//
// Every method that returns a stream returns a copy: mutating it, or the
// stream passed to Create / Update afterwards, MUST NOT reach the stored
// record.
//
// Stable since v1.5.
type SSFStreamStore interface {
	// Create stores a new stream. It MUST return [ErrConflict] when
	// another stream already has the same ID or the same ClientID, and
	// MUST make the ClientID check and the insert one atomic operation:
	// a receiver owns at most one stream.
	Create(ctx context.Context, s *SSFStream) error

	// Get returns the stream with the given ID, or [ErrNotFound].
	Get(ctx context.Context, id string) (*SSFStream, error)

	// GetByClient returns the stream owned by clientID, or [ErrNotFound].
	GetByClient(ctx context.Context, clientID string) (*SSFStream, error)

	// ListActive returns every stream whose Status is [SSFStreamEnabled]
	// or [SSFStreamPaused], in no particular order. Event fan-out reads
	// it once per event, so a backend SHOULD answer it in one round
	// trip. No active stream is an empty result and a nil error.
	ListActive(ctx context.Context) ([]*SSFStream, error)

	// Update replaces the stored stream with the same ID. ID and
	// ClientID identify the record and callers never change them. It
	// MUST return [ErrNotFound] when no stream has the ID.
	Update(ctx context.Context, s *SSFStream) error

	// Delete removes the stream and every event queued for it in
	// [SSFEventStore], so no delivery outlives its stream. It MUST
	// return [ErrNotFound] when no stream has the ID.
	Delete(ctx context.Context, id string) error
}

// SSFEventKind separates ordinary events from the control events a
// transmitter sends about the stream itself.
//
// Stable since v1.5.
type SSFEventKind string

// SSF event kinds.
const (
	// SSFEventKindEvent is an ordinary security event (CAEP / RISC). It
	// is the only kind held while the stream is paused and dropped while
	// it is disabled.
	//
	// Stable since v1.5.
	SSFEventKindEvent SSFEventKind = "event"

	// SSFEventKindStreamUpdated is a stream-updated control event (SSF
	// 1.0 §8.1.5), delivered whatever the stream's status.
	//
	// Stable since v1.5.
	SSFEventKindStreamUpdated SSFEventKind = "stream-updated"

	// SSFEventKindVerification is a verification control event (SSF 1.0
	// §8.1.4), delivered whatever the stream's status. A stream holds at
	// most one queued verification.
	//
	// Stable since v1.5.
	SSFEventKindVerification SSFEventKind = "verification"
)

// SSFEvent is one queued Security Event Token. The queue holds claims,
// not signed tokens: the library signs at delivery time with the key
// that is active then, so a retry carries the same jti under a current
// key.
//
// Stable since v1.5.
type SSFEvent struct {
	// JTI is the SET's jti. Primary key.
	JTI string

	// StreamID is the stream the event is queued for.
	StreamID string

	// Kind separates ordinary events from control events.
	Kind SSFEventKind

	// Delivery is the stream's delivery method at enqueue time, kept
	// current by [SSFEventStore.Retag]. It selects whether the push
	// worker ([SSFEventStore.ClaimDue]) or the poll endpoint
	// ([SSFEventStore.Pending]) sees the event.
	Delivery SSFDeliveryMethod

	// Held marks an ordinary event enqueued or retagged while its stream
	// was paused. Neither ClaimDue nor Pending returns a held event. The
	// library never sets Held on a control event.
	Held bool

	// Claims is the unsigned SET claims JSON, jti included. Backends
	// store and return the bytes verbatim.
	Claims []byte

	// Attempts is the number of failed push attempts so far.
	Attempts int

	// NextAttemptAt is the earliest instant the push worker may claim the
	// event. ClaimDue moves it forward by the lease.
	NextAttemptAt time.Time

	// ExpiresAt is when the event is dropped undelivered by
	// [SSFEventStore.DeleteExpired].
	ExpiresAt time.Time
}

// SSFEventStore is the outbound SET queue.
//
// Every method that returns an event returns a copy: mutating it, or the
// event passed to Enqueue afterwards, MUST NOT reach the stored record.
// No method consults ExpiresAt except DeleteExpired.
//
// Stable since v1.5.
type SSFEventStore interface {
	// Enqueue stores ev. It MUST return [ErrAlreadyExists] when an event
	// with the same JTI is queued. For Kind == [SSFEventKindVerification]
	// it MUST, in the same atomic operation, remove any verification
	// already queued for ev.StreamID, so a stream holds at most one.
	Enqueue(ctx context.Context, ev *SSFEvent) error

	// ClaimDue leases up to n events with Delivery == [SSFDeliveryPush],
	// Held == false and NextAttemptAt <= now, earliest NextAttemptAt
	// first, and sets their NextAttemptAt to now+lease. The returned
	// copies carry the new NextAttemptAt; Attempts is unchanged. n MUST
	// be positive.
	//
	// Selecting and leasing MUST be one atomic operation: an event is
	// returned to exactly one of several concurrent callers, and is not
	// returned again until its lease ends. That is what keeps several OP
	// replicas from pushing the same SET twice. An event whose lease ran
	// out without an Ack or Reschedule (its claimer died) is due again.
	ClaimDue(ctx context.Context, now time.Time, n int, lease time.Duration) ([]*SSFEvent, error)

	// Reschedule sets the event's NextAttemptAt and Attempts after a
	// failed push. It MUST return [ErrNotFound] when the event is no
	// longer queued.
	Reschedule(ctx context.Context, jti string, next time.Time, attempts int) error

	// Ack deletes the listed events of streamID. A JTI that is not
	// queued, or is queued for another stream, is ignored without error:
	// a receiver acknowledges only its own events.
	Ack(ctx context.Context, streamID string, jtis []string) error

	// Pending returns up to n events of streamID with Delivery ==
	// [SSFDeliveryPoll] and Held == false, in no particular order, and
	// reports whether more such events remain beyond them. It does not
	// lease or modify the events: they stay pending until acknowledged.
	// n MUST be positive.
	Pending(ctx context.Context, streamID string, n int) ([]*SSFEvent, bool, error)

	// Retag applies a status or delivery-method change to the events
	// queued for streamID. Every event takes Delivery = delivery, so
	// control events follow the stream to its new method; only events of
	// Kind == [SSFEventKindEvent] take Held = held, and control events
	// stay unheld.
	Retag(ctx context.Context, streamID string, delivery SSFDeliveryMethod, held bool) error

	// Purge deletes the events queued for streamID. With includeControl
	// false it deletes only Kind == [SSFEventKindEvent] events and keeps
	// stream-updated and verification events queued.
	Purge(ctx context.Context, streamID string, includeControl bool) error

	// DeleteExpired deletes every event with ExpiresAt <= now and
	// reports how many it deleted.
	DeleteExpired(ctx context.Context, now time.Time) (int, error)
}
